LANGUAGE_TABLES = {
    "ENGLISH": {},
    "CHINESE": ZH_HANS,
    "JAPANESE": JA,
}


def get_language(context):
    """Return the Book Factory language without depending on Blender locale."""
    if context is None:
        return "ENGLISH"
    addon = context.preferences.addons.get(__package__)
    return getattr(addon.preferences, "interface_language", "ENGLISH") if addon else "ENGLISH"


def tr(context, text):
    """Translate a Book Factory UI string using its own preference."""
    return LANGUAGE_TABLES.get(get_language(context), {}).get(text, text)

